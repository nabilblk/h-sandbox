import fs from "node:fs";

const directory = new URL("../examples/python-first-task/", import.meta.url);
const names = ["first_local.py", "first_sandbox.py", "first_model.py", "first_async.py", "first_existing.py"];
const snippets = Object.fromEntries(names.map(name => [name, fs.readFileSync(new URL(name, directory), "utf8").trimEnd()]));
const output = `// Generated by scripts/python-doc-snippets.mjs from runnable examples.\nexport const pythonExamples = ${JSON.stringify(snippets, null, 2)} as const;\n`;
const destination = new URL("../apps/web/src/python-doc-snippets.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (fs.readFileSync(destination, "utf8") !== output) throw new Error("Python documentation examples are stale");
} else {
  fs.writeFileSync(destination, output);
}
